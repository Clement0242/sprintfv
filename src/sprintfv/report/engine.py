"""PDF report engine shared by the packages (sprintfv, cpower, ...).

HTML + CSS rendered by WeasyPrint, charts drawn by matplotlib in the same
palette and typeface and embedded as vector SVG. Nothing in here knows about
sport: a package provides a Jinja template (extending ``base.html``) and a
context, and gets a PDF back.

Optional dependencies: ``pip install "<package>[report]"`` (weasyprint, jinja2,
matplotlib).
"""

from __future__ import annotations

import base64
import io
import mimetypes
from datetime import date
from pathlib import Path
from typing import Any

ASSETS = Path(__file__).resolve().parent / "assets"

PALETTE = {
    "navy": "#2C2F65", "red": "#C5243D", "gold": "#C59F69", "gold_light": "#E1CA88",
    "gold_dark": "#B38D52", "ink": "#1D2047", "text": "#3A3D63", "mut": "#7A7D9C",
    "line": "#DCDCE6", "light": "#F4F4F8", "sky": "#81BFE0", "violet": "#6559A7", "green": "#67AF5E",
}

TEXT = {  # the few words the engine itself writes
    "fr": {"athlete": "Athlète", "date": "Date", "test": "Test", "generated": "Rapport généré par"},
    "en": {"athlete": "Athlete", "date": "Date", "test": "Test", "generated": "Report generated by"},
}


def _require():
    try:
        import jinja2  # noqa: F401
        import weasyprint  # noqa: F401
    except ImportError as exc:  # pragma: no cover
        raise ImportError('PDF reports need the "report" extra: pip install "sprintfv[report]"') from exc


def mpl_theme() -> None:
    """Matplotlib in the report's palette and typeface."""
    import matplotlib as mpl
    from matplotlib import font_manager

    for f in ("Jost.ttf", "Jost-Italic.ttf"):
        try:
            font_manager.fontManager.addfont(str(ASSETS / f))
        except Exception:  # pragma: no cover - font is a nicety, never a failure
            pass
    mpl.rcParams.update({
        "font.family": "Jost", "font.size": 9, "axes.titlesize": 10, "axes.titleweight": "bold",
        "axes.titlecolor": PALETTE["navy"], "axes.labelcolor": PALETTE["text"], "axes.edgecolor": PALETTE["line"],
        "xtick.color": PALETTE["mut"], "ytick.color": PALETTE["mut"], "axes.spines.top": False,
        "axes.spines.right": False, "axes.grid": True, "grid.color": "#EBEBF2", "grid.linewidth": .8,
        "legend.frameon": False, "svg.fonttype": "path", "figure.dpi": 150,
        "axes.prop_cycle": mpl.cycler(color=[PALETTE["navy"], PALETTE["red"], PALETTE["gold"],
                                             PALETTE["sky"], PALETTE["violet"], PALETTE["green"]]),
    })


def fig_to_uri(fig) -> str:
    """Embed a matplotlib figure as a vector SVG data URI, then close it."""
    import matplotlib.pyplot as plt

    buf = io.BytesIO()
    fig.savefig(buf, format="svg", bbox_inches="tight")
    plt.close(fig)
    return "data:image/svg+xml;base64," + base64.b64encode(buf.getvalue()).decode()


def file_to_uri(path: str | Path | None) -> str | None:
    if not path:
        return None
    p = Path(path)
    mime = mimetypes.guess_type(p.name)[0] or "image/png"
    return f"data:{mime};base64," + base64.b64encode(p.read_bytes()).decode()


def outlined_number(n: int | str) -> str:
    """The large outlined section number of the charter, as inline SVG."""
    return (f'<svg viewBox="0 0 64 46" xmlns="http://www.w3.org/2000/svg"><text x="0" y="40" font-family="Jost" '
            f'font-size="46" font-weight="800" fill="none" stroke="#2C2F65" stroke-width="1.6">{int(n):02d}</text></svg>')


def fmt(x: Any, digits: int = 2, lang: str = "fr") -> str:
    """Number formatting in the report's language (decimal comma in French)."""
    if x is None:
        return "—"
    try:
        s = f"{float(x):,.{digits}f}"
    except (TypeError, ValueError):
        return str(x)
    if lang == "fr":
        s = s.replace(",", " ").replace(".", ",")
    return s


def render_pdf(template_dir: Path, template: str, context: dict[str, Any], out: str | Path) -> Path:
    """Render ``template`` (Jinja, extending base.html) with ``context`` to a PDF file."""
    _require()
    import jinja2
    import weasyprint

    lang = context.get("lang", "fr")
    env = jinja2.Environment(loader=jinja2.FileSystemLoader([str(template_dir), str(ASSETS)]),
                             autoescape=jinja2.select_autoescape(["html"]))
    env.filters["fmt"] = lambda x, d=2: fmt(x, d, lang)
    env.globals["outlined_number"] = outlined_number
    ctx = {"today": date.today().isoformat(), "t": TEXT.get(lang, TEXT["en"]), **context}
    ctx["logo_uri"] = file_to_uri(context.get("logo"))
    html = env.get_template(template).render(**ctx)
    out = Path(out)
    weasyprint.HTML(string=html, base_url=str(ASSETS)).write_pdf(out)
    return out
